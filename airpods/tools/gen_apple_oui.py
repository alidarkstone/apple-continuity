"""Regenerates src/AirPodsWin.Core/AppleOui.g.cs: every IEEE MA-L block (OUI)
registered to Apple, Inc. Input is the IEEE registry as JSON {"AABBCC": "Org..."},
e.g. index.json from the npm package oui-data (a mirror of standards-oui.ieee.org).

    python gen_apple_oui.py path/to/index.json
"""
import json
import sys
from pathlib import Path

registry = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
apple = sorted(int(k, 16) for k, v in registry.items() if v.lower().startswith("apple, inc"))

lines = []
for i in range(0, len(apple), 8):
    lines.append("        " + ", ".join(f"0x{o:06X}" for o in apple[i:i + 8]) + ",")

out = Path(__file__).resolve().parent.parent / "src" / "AirPodsWin.Core" / "AppleOui.g.cs"
out.write_text(
    "// <auto-generated> by tools/gen_apple_oui.py from the IEEE MA-L registry. Do not edit. </auto-generated>\n"
    "namespace AirPodsWin.Core;\n\n"
    "public static partial class AppleDevice\n{\n"
    f"    /// <summary>{len(apple)} IEEE OUIs registered to Apple, Inc., sorted.</summary>\n"
    "    static readonly uint[] AppleOuis =\n    {\n" + "\n".join(lines) + "\n    };\n}\n",
    encoding="utf-8",
)
print(f"{len(apple)} Apple OUIs -> {out}")
